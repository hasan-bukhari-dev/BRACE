import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {JSDOM}=await import(pathToFileURL(path.join(root,'work/dom-test/node_modules/jsdom/lib/api.js')).href);
const runtime=path.join(root,'work/dom-test/navigation');await fs.mkdir(runtime,{recursive:true});
await fs.writeFile(path.join(runtime,'package.json'),'{"type":"module"}');
for(const file of ['wordmark.js','identity.js'])await fs.copyFile(path.join(root,'brace_app/static/js',file),path.join(runtime,file));
const html=await fs.readFile(path.join(root,'brace_app/static/index.html'),'utf8');
const dom=new JSDOM(html,{url:'http://127.0.0.1:8765'});
globalThis.document=dom.window.document;globalThis.window=dom.window;
globalThis.ResizeObserver=class{observe(){}};globalThis.requestAnimationFrame=fn=>fn();
Object.defineProperty(document,'fonts',{value:{ready:Promise.resolve()}});
const {initWordmark}=await import(pathToFileURL(path.join(runtime,'wordmark.js')).href);
const {identities}=await import(pathToFileURL(path.join(runtime,'identity.js')).href);
const commits=[];const controller=initWordmark(key=>{commits.push(key);controller.select(key)});
const nav=document.querySelector('#wordmark'),buttons=[...nav.querySelectorAll('button')];
buttons.forEach(b=>b.disabled=false);
assert(!document.querySelector('.app-header').contains(nav));
assert(document.querySelector('.tool-navigation').contains(nav));
controller.select('study');
for(const [i,name] of ['BRACE','RACE','ACE','CE','EMBRACE'].entries()){
 buttons[i].onpointerenter();
 assert.equal(document.querySelector('#navigation-purpose').textContent,name+' — '+identities[name]);
 assert.equal(commits.length,0,'preview must not navigate');
 assert.equal(buttons[0].getAttribute('aria-current'),'page');
}
nav.onpointerleave();assert.equal(nav.dataset.preview,'study');
buttons[1].focus();buttons[1].dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));
assert.equal(document.activeElement,buttons[2]);assert.equal(nav.dataset.preview,'ace');
nav.onpointerleave();assert.equal(nav.dataset.preview,'ace','pointer exit preserves keyboard preview');
buttons[2].click();assert.equal(commits.at(-1),'ace');assert.equal(buttons[2].getAttribute('aria-current'),'page');
buttons[2].dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'End',bubbles:true}));assert.equal(document.activeElement,buttons[4]);
buttons[4].dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));assert.equal(nav.dataset.preview,'ace');
for(const [id,label] of [['home-genes','RACE'],['home-predictions','ACE'],['home-distributions','CE']])assert.equal(document.querySelector('#'+id+' .tool-monogram').textContent,label);
assert.equal(document.querySelector('#navigation-purpose').getAttribute('aria-live'),null,'hover description should not repeatedly announce');
const ids=[...document.querySelectorAll('[id]')].map(el=>el.id);assert.equal(new Set(ids).size,ids.length);
console.log('PASS: centered navigation; five full expansions; preview versus selection; keyboard arrows/End/Escape; focus retention; question labels; unique IDs. DOM contract only, not rendered accessibility certification.');
